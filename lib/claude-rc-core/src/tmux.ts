import { createHash } from "node:crypto";
import { constants } from "node:os";
import { join } from "node:path";
import type { RcPaths } from "./paths";
import type { Exec } from "./supervisor-types";

/** Every repo gets its own private tmux server with exactly one session of this name. */
export const TMUX_SESSION = "rc";

const SOCKET_MAX = 100; // sun_path is 104 on macOS, 108 on Linux; keep headroom

/**
 * Socket for one repo's tmux server. One server per repo on purpose: a tmux server lives in the
 * cgroup of the unit that started it, so a shared server would die with whichever unit came first.
 */
export function tmuxSocketFor(
  paths: Pick<RcPaths, "runDir">,
  env: Record<string, string | undefined>,
  name: string,
): string {
  const normal = join(paths.runDir, "tmux", `${name}.sock`);
  if (normal.length < SOCKET_MAX) return normal;
  const uid = typeof process.getuid === "function" ? process.getuid() : 0;
  const h = createHash("sha256").update(`${paths.runDir}\0${name}`).digest("hex").slice(0, 12);
  return join(env.TMPDIR ?? "/tmp", `claude-rc-${uid}`, `${h}.sock`);
}

/** Minimal tmux config; deliberately not the user's ~/.tmux.conf so behaviour is predictable. */
export function tmuxConf(name: string): string {
  const label = `claude-rc: ${name}`.replace(/[^A-Za-z0-9 ._:-]/g, "_");
  return [
    "# generated by claude-rc-daemon; do not edit",
    "set -g remain-on-exit on", // keep a dead pane so its exit status can be read
    "set -g window-size latest",
    "set -g history-limit 20000",
    "set -g mouse on",
    "set -g status-left-length 40",
    `set -g status-left "[${label}] "`,
    'set -g status-right "detach: Ctrl-b d"',
    "",
  ].join("\n");
}

export const attachArgv = (tmuxBin: string, socket: string): string[] => [
  tmuxBin,
  "-S",
  socket,
  "attach",
  "-t",
  TMUX_SESSION,
];

const quote = (s: string) =>
  /^[A-Za-z0-9_@%+=:,./-]+$/.test(s) ? s : `'${s.replace(/'/g, `'\\''`)}'`;

/** What to show a human to connect to the session. */
export const attachCommandLine = (socket: string): string =>
  ["tmux", "-S", socket, "attach", "-t", TMUX_SESSION].map(quote).join(" ");

export interface SessionProbe {
  dead: boolean;
  /** Exit code, or 128+signal when the pane's process was killed by a signal. */
  exitStatus?: number;
  pid?: number;
  /** Epoch ms of the last pane output. */
  lastActivity?: number;
  /** Number of clients attached to the session. */
  attached: number;
  /** Last lines of the pane, blank trailing lines removed. */
  tail: string[];
}

/** tmux prints pane_dead_signal as a number (older) or a name like "TERM"/"SIGTERM" (newer). */
export function signalNumber(v: string): number | undefined {
  if (/^\d+$/.test(v)) return Number(v) > 0 ? Number(v) : undefined;
  const name = v.trim().toUpperCase();
  if (!name) return undefined;
  return (constants.signals as Record<string, number>)[
    name.startsWith("SIG") ? name : `SIG${name}`
  ];
}

const FORMAT =
  "#{pane_dead}|#{pane_dead_status}|#{pane_dead_signal}|#{pane_pid}|#{window_activity}|#{session_attached}";

/** Ask a repo's tmux server about its session. null = no server or no session. Never throws. */
export async function probeSession(
  exec: Exec,
  tmuxBin: string,
  socket: string,
  tailLines = 30,
): Promise<SessionProbe | null> {
  const base = [tmuxBin, "-S", socket];
  const r = await exec([...base, "list-panes", "-t", TMUX_SESSION, "-F", FORMAT]).catch(() => null);
  if (!r || r.code !== 0) return null;
  const f = r.stdout.split("\n")[0]?.split("|");
  if (!f || f.length !== 6) return null;
  const [dead, status, sig, pid, act, att] = f as [string, string, string, string, string, string];
  if (!/^[01]$/.test(dead) || !/^\d+$/.test(att)) return null;

  // -S - reads scrollback too; a dead pane shows only its banner without it.
  const cap =
    tailLines > 0
      ? await exec([
          ...base,
          "capture-pane",
          "-p",
          "-t",
          TMUX_SESSION,
          "-S",
          `-${Math.max(tailLines * 2, 60)}`,
        ]).catch(() => null)
      : null;
  // Blank rows (a fresh pane is mostly blank) and tmux's own "Pane is dead" banner carry no news.
  const lines =
    cap && cap.code === 0
      ? cap.stdout.split("\n").filter((l) => l.trim() !== "" && !l.startsWith("Pane is dead"))
      : [];

  const sigNo = signalNumber(sig);
  const exitStatus =
    dead !== "1"
      ? undefined
      : sigNo !== undefined
        ? 128 + sigNo
        : /^\d+$/.test(status)
          ? Number(status)
          : undefined;
  return {
    dead: dead === "1",
    ...(exitStatus !== undefined ? { exitStatus } : {}),
    ...(/^\d+$/.test(pid) ? { pid: Number(pid) } : {}),
    ...(/^\d+$/.test(act) ? { lastActivity: Number(act) * 1000 } : {}),
    attached: Number(att),
    tail: tailLines > 0 ? lines.slice(-tailLines) : [],
  };
}

/** Command prefix that runs the rest of argv under the tmux keeper (`<self> tmux-run ... --`). */
export const tmuxRunPrefix = (
  selfCmd: string[],
  tmuxBin: string,
  socket: string,
  name: string,
  logFile?: string,
): string[] => [
  ...selfCmd,
  "tmux-run",
  "--tmux",
  tmuxBin,
  "--socket",
  socket,
  "--name",
  name,
  ...(logFile ? ["--log", logFile] : []),
  "--",
];
